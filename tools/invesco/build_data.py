#!/usr/bin/env python3
"""Assemble ../../invesco_etf_data.js (loaded by invesco-etf.html) from:

  tase_funds.json     security numbers, fees, reference index        (browser-collected, rarely changes)
  holdings_raw.json   top-10 + country/sector exposure from Invesco  (browser-collected, refresh monthly)
  fund_text_he.json   Hebrew names, descriptions, translations       (hand-edited)
  prices.json         daily ILS closes                               (update_prices.py, fully automatic)

Returns are PRICE returns of the TASE-listed unit in ILS (close-to-close). The price feed carries no
distribution adjustment, so a distributing fund understates its total return by its yield.
A full-year return needs a close on or before 31 Dec of the previous year; otherwise it is withheld and
the reason is recorded (listing date). In a fund's listing year we also keep the partial return since
listing, flagged as partial, for the information table only.
"""
import datetime, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "invesco_etf_data.js")
load = lambda n: json.load(open(os.path.join(HERE, n), encoding="utf-8"))

tase, raw, text, prices = load("tase_funds.json"), load("holdings_raw.json"), load("fund_text_he.json"), load("prices.json")
aum_file = load("aum.json")

# Fund size is only used to ORDER the page. Two funds are quoted in EUR, so for the ordering they are
# converted at an approximate rate; the displayed figure stays in Invesco's own currency.
EURUSD_FOR_SORT = 1.15
def aum_usd(txt):
    m = re.match(r"([$€])([0-9.,]+)([MB])$", txt)
    v = float(m.group(2).replace(",", "")) * (1e9 if m.group(3) == "B" else 1e6)
    return v * (EURUSD_FOR_SORT if m.group(1) == "€" else 1)

CUR = re.compile(r"(?:IUSD|AUSD|USD|JPY|KRW|HKD|CNY|TWD)\s*[0-9.]*\s*(?:NPV)?$")
def clean(name):
    n = name.strip()
    n = CUR.sub("", n).strip()
    n = re.sub(r"\s+(NPV|ORD)$", "", n).strip()
    n = re.sub(r"\s+ORD$", "", n).strip()
    return n or name

def pairs(s):
    return [(a.rsplit("|", 1)[0], float(a.rsplit("|", 1)[1])) for a in s.split(";")] if s else []

missing = set()
def tr(dic, k):
    if k in dic: return dic[k]
    missing.add(k); return k

def last_on_or_before(rows, date):
    v = None
    for r in rows:
        if r[0] <= date: v = r
        else: break
    return v

asof = max(rows[-1][0] for rows in prices.values())
cur_year = int(asof[:4])
years = list(range(2022, cur_year + 1))

funds = []
for f in tase["funds"]:
    sec, t = f["sec"], f["ticker"]
    rows = prices[t]
    first = rows[0]
    last = rows[-1]
    rets = {}
    for y in years:
        start = last_on_or_before(rows, "%d-12-31" % (y - 1))
        end = last_on_or_before(rows, "%d-12-31" % y) if y < cur_year else last
        if end is None or end[0] < "%d-01-01" % y:
            rets[y] = {"r": None, "why": "none"}               # not trading at all in that year
        elif start is None:
            rets[y] = {"r": None, "why": "listed", "partial": round((end[1] / first[1] - 1) * 100, 2),
                       "from": first[0], "to": end[0]}
        else:
            rets[y] = {"r": round((end[1] / start[1] - 1) * 100, 2), "from": start[0], "to": end[0]}
    dist = any(abs(c - a) / c > 1e-4 for _, c, a in rows)
    h = raw["funds"][sec]
    d = {
        "sec": sec, "ticker": t, "isin": h["isin"],
        "name": text["funds"][sec]["name"], "nameEn": f["fullName"], "desc": text["funds"][sec]["desc"],
        "fee": f["fee"], "ccy": f["ccy"], "ref": f["ref"],
        "aum": aum_file["aum"][sec], "aumUsd": aum_usd(aum_file["aum"][sec]),
        "firstTrade": first[0], "lastDate": last[0], "lastPrice": last[1],
        "stale": (datetime.date.fromisoformat(asof) - datetime.date.fromisoformat(last[0])).days > 5,
        "adjDiffers": dist,
        "returns": {str(y): v for y, v in rets.items()},
    }
    if h.get("country"):
        d["country"] = [[tr(text["countries"], n), w, n] for n, w in pairs(h["country"])]
    if h.get("sector"):
        d["sector"] = [[tr(text["sectors"], n), w, n] for n, w in pairs(h["sector"])]
    if h.get("top10"):
        d["top10"] = [[clean(n), w] for n, w in pairs(h["top10"])]
    if h.get("creditQuality"):
        d["credit"] = [[tr(text["ratings"], n), w] for n, w in pairs(h["creditQuality"])]
        d["rating"] = [[n, w] for n, w in pairs(h["rating"])]
    funds.append(d)

funds.sort(key=lambda d: -d["aumUsd"])          # biggest fund first, in the table and in the calculator
data = {"aumAsOf": aum_file["asOf"], "generated": datetime.date.today().isoformat(), "pricesAsOf": asof, "years": years, "funds": funds}
open(OUT, "w", encoding="utf-8").write(
    "/* generated by tools/invesco/build_data.py - do not edit by hand */\n"
    "window.INVESCO_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")

print("wrote", os.path.normpath(OUT), os.path.getsize(OUT), "bytes;", len(funds), "funds; prices as of", asof)
if missing: print("WARNING untranslated names:", sorted(missing))
if any(f["adjDiffers"] for f in funds): print("NOTE: some funds now carry adjusted closes - review the 'price return' wording")
for f in funds:
    if f["stale"]: print("stale price:", f["ticker"], "last trade", f["lastDate"])
